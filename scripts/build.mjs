// Builds the static web app into dist/: one bundled script, the stylesheet, the art, the manifest and a
// service worker for offline use. The Yosef case study is NOT included; it is imported as a file.

import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'dist');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

await build({
  entryPoints: [path.join(root, 'public/js/app.js')],
  bundle: true,
  format: 'esm',
  target: ['es2022', 'safari16'],
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  outfile: path.join(out, 'app.js'),
  logLevel: 'warning',
});

for (const f of ['index.html', 'styles.css', 'manifest.webmanifest', 'art/icon.svg']) {
  fs.mkdirSync(path.dirname(path.join(out, f)), { recursive: true });
  fs.copyFileSync(path.join(root, 'public', f), path.join(out, f));
}

// Guard: the case study must never end up in the published site.
const bundle = fs.readFileSync(path.join(out, 'app.js'), 'utf8');
for (const marker of ['nemeparlesplusjamais', 'e_2025_07_06_rain', 'fruitz matching']) {
  if (bundle.includes(marker)) throw new Error(`Case-study content leaked into the bundle (${marker})`);
}

// Service worker: cache the app shell so Oracle opens offline. The cache name changes with the build.
const files = ['./', 'index.html', 'app.js', 'styles.css', 'manifest.webmanifest', 'art/icon.svg'];
const hash = crypto.createHash('sha256');
for (const f of files.slice(1)) hash.update(fs.readFileSync(path.join(out, f)));
const version = hash.digest('hex').slice(0, 12);
fs.writeFileSync(path.join(out, 'sw.js'), `// Generated by scripts/build.mjs
const CACHE = 'oracle-${version}';
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== location.origin) return; // never touch API calls
  e.respondWith(fetch(e.request).then((r) => { const copy = r.clone(); caches.open(CACHE).then((c) => c.put(e.request, copy)); return r; }).catch(() => caches.match(e.request).then((r) => r || caches.match('index.html'))));
});
`);
// For hosts that need it: GitHub Pages should not run Jekyll on this folder.
fs.writeFileSync(path.join(out, '.nojekyll'), '');

const size = (f) => `${(fs.statSync(path.join(out, f)).size / 1024).toFixed(0)} KB`;
console.log(`Built dist/ (app.js ${size('app.js')}, version ${version})`);
